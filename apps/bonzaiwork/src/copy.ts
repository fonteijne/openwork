/** "Sanne", "Sanne en Ahmed", "Sanne, Ahmed en Lotte". */
export function listNames(names: string[]): string {
  if (names.length <= 1) return names[0] ?? "";
  return `${names.slice(0, -1).join(", ")} en ${names.at(-1) ?? ""}`;
}

