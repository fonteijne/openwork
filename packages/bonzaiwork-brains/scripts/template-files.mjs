#!/usr/bin/env node
/**
 * Writes src/template-files.js from templates/: one text import per file, so
 * bun bundles every template into server-hooks.js and each release ships them.
 *
 *   pnpm --filter @bonzaiwork/brains templates          rewrite the manifest
 *   pnpm --filter @bonzaiwork/brains templates --check  fail when it is out of date
 *
 * Run it after adding, renaming or removing a file under templates/ (editing a
 * file needs nothing). test/okf.test.ts fails when the manifest is stale.
 * Only text files: a template is written as UTF-8 text.
 */
import { readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const templates = join(root, "templates");
const target = join(root, "src", "template-files.js");
/** Notes for maintainers, not part of any template. */
const SKIPPED = new Set(["vendor/README.md"]);

async function walk(dir) {
  const files = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(path)));
    else if (entry.isFile()) files.push(relative(templates, path).split(sep).join("/"));
  }
  return files;
}

const files = (await walk(templates)).filter((file) => !SKIPPED.has(file)).sort();
const lines = [
  "// Generated by scripts/template-files.mjs from templates/; do not edit by hand.",
  "// Run `pnpm --filter @bonzaiwork/brains templates` after adding, renaming or removing a template file.",
  "// Each file is bundled as text by bun; src/template-files.d.ts gives the type, so any file type works.",
  ...files.map((file, index) => `import t${index} from ${JSON.stringify(`../templates/${file}`)} with { type: "text" };`),
  "",
  "/** Template file (path under templates/) → content. */",
  "export const TEMPLATE_FILES = new Map([",
  ...files.map((file, index) => `  [${JSON.stringify(file)}, t${index}],`),
  "]);",
  "",
];
const next = lines.join("\n");
const current = await readFile(target, "utf8").catch(() => null);

if (process.argv.includes("--check")) {
  if (current !== next) {
    console.error("src/template-files.js is out of date: run `pnpm --filter @bonzaiwork/brains templates`.");
    process.exit(1);
  }
  console.log(`src/template-files.js is up to date (${files.length} files).`);
} else if (current === next) {
  console.log(`src/template-files.js is up to date (${files.length} files).`);
} else {
  await writeFile(target, next);
  console.log(`Wrote src/template-files.js (${files.length} files).`);
}
