#!/usr/bin/env node
/**
 * Regenerates `src/files.ts` (every harness file as a text import) and records
 * the fingerprint of each item for the current `harness.json` version. Earlier
 * versions' fingerprints stay, so a brain's unchanged copy of an older version
 * is still recognised (docs/bonzaiwork/brein-harnas-plan.md, H3).
 *
 *   pnpm --filter @bonzaiwork/harness manifest
 *   node scripts/manifest.mjs --check   (exit 1 when something is stale)
 */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const harnessDir = join(root, "harness");
const check = process.argv.includes("--check");

function walk(dir) {
  const files = [];
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...walk(path));
    else if (statSync(path).isFile()) files.push(relative(harnessDir, path).split("\\").join("/"));
  }
  return files;
}

const files = walk(harnessDir);
const lines = [
  "// Generated by scripts/manifest.mjs (test/harness.test.ts checks it is current). Each file is bundled as text.",
  ...files.map((file, index) => `import t${index} from "../harness/${file}" with { type: "text" };`),
  "",
  "/** Harness file (path under harness/) → content. */",
  "export const HARNESS_FILES: ReadonlyMap<string, string> = new Map([",
  ...files.map((file, index) => `  [${JSON.stringify(file)}, t${index}],`),
  "]);",
  "",
];
const filesTs = lines.join("\n");

const manifestPath = join(root, "harness.json");
const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));

/** Same rule as src/index.ts itemFingerprint(): sorted files, `harness:` frontmatter line stripped. */
function stripStamp(content) {
  return content.replace(/^(---\r?\n[\s\S]*?)^harness:[^\n]*\r?\n([\s\S]*?^---)/m, "$1$2");
}
function fingerprint(paths) {
  // Paths inside the item (`SKILL.md`, `assets/x.md`), the same as src/index.ts sees them in a brain.
  const inside = (path) => (path.startsWith("skills/") ? path.split("/").slice(2).join("/") : path.split("/").at(-1));
  const hash = createHash("sha256");
  for (const path of [...paths].sort((a, b) => (inside(a) < inside(b) ? -1 : inside(a) > inside(b) ? 1 : 0))) {
    hash.update(`${inside(path)}\0${stripStamp(readFileSync(join(harnessDir, path), "utf8"))}\0`);
  }
  return hash.digest("hex");
}
const items = {};
for (const file of files) {
  const [kind, name] = file.split("/");
  if (kind === "skills" && name) items[`skill:${name}`] = [...(items[`skill:${name}`] ?? []), file];
  else if (kind === "commands" && name?.endsWith(".md")) items[`command:${name.slice(0, -3)}`] = [file];
  else if (kind === "agents" && name?.endsWith(".md")) items[`agent:${name.slice(0, -3)}`] = [file];
}
const next = { version: manifest.version, items: { ...manifest.items } };
for (const [key, paths] of Object.entries(items)) {
  const versions = { ...(next.items[key]?.versions ?? {}) };
  versions[manifest.version] = fingerprint(paths);
  next.items[key] = { versions };
}
for (const key of Object.keys(next.items)) if (!items[key]) next.items[key] = { ...next.items[key], removed: true };
const manifestJson = `${JSON.stringify(next, null, 2)}\n`;

const currentFiles = (() => { try { return readFileSync(join(root, "src/files.ts"), "utf8"); } catch { return ""; } })();
const stale = currentFiles !== filesTs || readFileSync(manifestPath, "utf8") !== manifestJson;
if (check) {
  if (stale) { console.error("harness: src/files.ts or harness.json is stale; run pnpm --filter @bonzaiwork/harness manifest"); process.exit(1); }
  console.log("harness: manifest is current");
} else {
  writeFileSync(join(root, "src/files.ts"), filesTs);
  writeFileSync(manifestPath, manifestJson);
  console.log(`harness ${manifest.version}: ${files.length} files, ${Object.keys(items).length} items`);
}
