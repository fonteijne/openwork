/**
 * Keeps PATCHES.md honest (docs/bonzaiwork/README.md, "Git"): every upstream
 * file this fork changes must have a row, every row must still be a change,
 * and the table should stay short. Diffs against the commit in
 * bonzaiwork.upstream.json, which each upstream-sync merge updates.
 */
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";

const OWN = [
  "apps/bonzaiwork/",
  "packages/bonzaiwork-",
  "docs/bonzaiwork/",
  "scripts/bonzaiwork/",
  ".github/workflows/bonzaiwork.yml",
  "apps/desktop/electron-builder.bonzaiwork.mjs",
  "PATCHES.md",
  "bonzaiwork.upstream.json",
];
// Regenerated by pnpm from the manifests; never hand-merged.
const GENERATED = ["pnpm-lock.yaml"];
const SOFT_LIMIT = 10;

const base = JSON.parse(readFileSync("bonzaiwork.upstream.json", "utf8")).commit;
const changes = execFileSync("git", ["diff", "--name-status", "--no-renames", base, "HEAD"], { encoding: "utf8" })
  .trim().split("\n").filter(Boolean).map((line) => {
    const [status, path] = line.split("\t");
    return { status, path };
  });
const upstreamChanges = changes.filter(({ path }) => !OWN.some((own) => path.startsWith(own)) && !GENERATED.includes(path));

const listed = new Set([...readFileSync("PATCHES.md", "utf8").matchAll(/^\|\s*`([^`]+)`/gm)].map((match) => match[1]));
const missing = upstreamChanges.filter(({ path }) => !listed.has(path));
const stale = [...listed].filter((path) => !upstreamChanges.some((change) => change.path === path));

for (const { status, path } of missing) console.error(`PATCHES.md misses ${status === "A" ? "new file" : "change"}: ${path}`);
for (const path of stale) console.error(`PATCHES.md lists ${path}, which no longer differs from upstream`);
const patched = upstreamChanges.filter(({ status }) => status !== "A").length;
console.log(`${patched} patched upstream file(s), ${upstreamChanges.length - patched} new file(s) in upstream folders`);
if (patched > SOFT_LIMIT) console.warn(`More than ${SOFT_LIMIT} patched upstream files: revisit the approach (README "Gouden regel").`);
process.exit(missing.length || stale.length ? 1 : 0);
